    await pg.evaluate("window.scrollTo(0,0)"); await pg.wait_for_timeout(300)
    await pg.screenshot(path=f'{S}/a2-hoje.png')
    await pg.click('.hj-go'); await pg.wait_for_timeout(1500)
    await pg.screenshot(path=f'{S}/a3-lista.png')
    await pg.click('#ex-card-0'); await pg.wait_for_timeout(800)
    await pg.screenshot(path=f'{S}/a4-sheet.png')
    await pg.click('.sheet.v3 .cta'); await pg.wait_for_timeout(800)
    await pg.screenshot(path=f'{S}/a5-descanso.png')
    await pg.click('.rest-bts .pl'); await pg.wait_for_timeout(300)
    await pg.click('.sheet.v3 .cta'); await pg.wait_for_timeout(500); await pg.click('.rest-min'); await pg.wait_for_timeout(300)
    await pg.screenshot(path=f'{S}/a6-sheet2.png')
    # prancha (último) -> tempo
    n=await pg.evaluate("document.querySelectorAll('#session-stack .ex-row').length")
    await pg.evaluate("ForjaGymUI.closeExSheet()"); await pg.wait_for_timeout(400)
    await pg.evaluate("ForjaGymUI.pularRest(true)")
