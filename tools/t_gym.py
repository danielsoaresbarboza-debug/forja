    await pg.goto('http://localhost:8766/index.html'); await pg.wait_for_timeout(2500)
    await pg.evaluate("document.querySelector('[data-tab=academia]').click()"); await pg.wait_for_timeout(1000)
    await pg.screenshot(path=f'{S}/a1-vazio.png')
