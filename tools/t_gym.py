    await pg.evaluate("window.scrollTo(0,0)"); await pg.wait_for_timeout(500)
    await pg.screenshot(path=f'{S}/a11-depois.png',full_page=True)
    print('ERROS',json.dumps(errs,ensure_ascii=False,indent=1))
